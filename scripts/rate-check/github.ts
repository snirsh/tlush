import { writeFileSync } from "node:fs";
import type { BtlPage } from "./btl";
import type { Report } from "./compare";
import { run } from "./proc";
import { hashMarker, hashOf, readHash, renderIssueBody, renderPrBody, type CommandResult, type FileChange } from "./render";

export const BOT_BRANCH = "bot/rate-update";
export const LABEL = "rate-checker";
export const ISSUE_TITLE = "Rate checker: could not verify official rates";

/** The side effects `sync` needs. The workflow uses the real one; tests record calls. */
export interface Shell {
  /** Runs a command, throws on a non-zero exit, returns stdout. */
  exec(cmd: string, args: string[], stdin?: string): Promise<string>;
  /** Runs a check command and reports pass or fail with the output tail. */
  check(command: string): Promise<CommandResult>;
  writeFile(path: string, text: string): void;
}

export const realShell: Shell = {
  async exec(cmd, args, stdin) {
    const r = await run(cmd, args, stdin);
    if (r.code !== 0) throw new Error(`${cmd} ${args.join(" ")} exited ${r.code}:\n${r.stdout}${r.stderr}`);
    return r.stdout.toString("utf8");
  },
  async check(command) {
    const [cmd, ...args] = command.split(" ");
    const r = await run(cmd, args);
    const out = `${r.stdout.toString("utf8")}${r.stderr}`;
    return { command, ok: r.code === 0, tail: out.trim().split("\n").slice(-60).join("\n") };
  },
  writeFile: (path, text) => writeFileSync(path, text),
};

export interface SyncArgs {
  report: Report;
  changes: FileChange[];
  notes: string[];
  btl: BtlPage;
  base: string;
  runUrl: string;
}

/** Converges the bot branch, the bot PR and the bot issue on this run's findings. Safe to rerun. */
export async function sync(args: SyncArgs, sh: Shell = realShell): Promise<void> {
  await syncPullRequest(args, sh);
  await syncIssue(args.report, args.runUrl, sh);
}

async function openItem(sh: Shell, kind: "issue" | "pr", filter: string[]): Promise<{ number: number; body: string } | undefined> {
  const list = JSON.parse(await sh.exec("gh", [kind, "list", "--state", "open", "--json", "number,body", "--limit", "5", ...filter]));
  return list[0];
}

async function syncPullRequest({ report, changes, notes, btl, base, runUrl }: SyncArgs, sh: Shell): Promise<void> {
  const pr = await openItem(sh, "pr", ["--head", BOT_BRANCH]);
  if (changes.length === 0) {
    if (pr) {
      await sh.exec("gh", ["pr", "close", String(pr.number), "--comment", `The spec on \`${base}\` now matches the official figures (run ${runUrl}). Closing.`]);
    }
    return;
  }
  const hash = hashOf(report.years);
  if (pr && readHash(pr.body) === hash) {
    console.log(`PR #${pr.number} already reflects these findings.`);
    return;
  }

  for (const c of changes) sh.writeFile(c.path, c.after);
  const results = [await sh.check("bun run test"), await sh.check("bun run build")];
  const body = renderPrBody({ report, btl, results, notes, runUrl, hash });
  const years = report.years
    .filter((y) => y.kind === "new" || (y.kind === "existing" && y.checks.some((c) => c.status === "diff")))
    .map((y) => (y.kind === "new" ? `new ${y.year}` : String(y.year)));
  const title = `data: official tax figures changed (${years.join(", ")})`;

  await sh.exec("git", ["config", "user.name", "github-actions[bot]"]);
  await sh.exec("git", ["config", "user.email", "41898282+github-actions[bot]@users.noreply.github.com"]);
  await sh.exec("git", ["add", "--", ...changes.map((c) => c.path)]);
  await sh.exec("git", ["commit", "-m", `${title}\n\nGenerated by the rate checker: ${runUrl}`]);
  await sh.exec("git", ["push", "--force", "origin", `HEAD:refs/heads/${BOT_BRANCH}`]);

  if (pr) await sh.exec("gh", ["pr", "edit", String(pr.number), "--title", title, "--body-file", "-"], body);
  else await sh.exec("gh", ["pr", "create", "--head", BOT_BRANCH, "--base", base, "--title", title, "--body-file", "-"], body);
}

async function syncIssue(report: Report, runUrl: string, sh: Shell): Promise<void> {
  const issue = await openItem(sh, "issue", ["--label", LABEL]);
  if (report.problems.length === 0) {
    if (issue) await sh.exec("gh", ["issue", "close", String(issue.number), "--comment", `Resolved by run ${runUrl}`]);
    return;
  }
  const hash = hashOf(report.problems);
  const body = renderIssueBody(report.problems, runUrl, hash);
  if (!issue) {
    await sh.exec("gh", ["label", "create", LABEL, "--color", "D93F0B", "--description", "Opened by the monthly rate checker", "--force"]);
    await sh.exec("gh", ["issue", "create", "--title", ISSUE_TITLE, "--label", LABEL, "--body-file", "-"], body);
  } else if (readHash(issue.body) !== hash) {
    await sh.exec("gh", ["issue", "edit", String(issue.number), "--body-file", "-"], body);
    await sh.exec("gh", ["issue", "comment", String(issue.number), "--body", `Findings changed in run ${runUrl}. ${hashMarker(hash)}`]);
  }
}
